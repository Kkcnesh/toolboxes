RUN_PY_TEMPLATE = '''# run.py -- generated by Toolbox build server
# This is the entry point Toolbox uses to launch this tool.
# Args are passed as JSON via stdin, results returned via stdout.
import json
import os
import runpy
import sys

sys.path.insert(0, os.path.dirname(__file__))

ENTRY_POINT = {entry_point!r}
REPO_DIR = os.path.join(os.path.dirname(__file__), "repo")


def _load_args():
    raw = sys.stdin.read()
    if not raw.strip():
        return []
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        return []
    if isinstance(payload, list):
        return [str(item) for item in payload]
    if isinstance(payload, dict):
        return [str(item) for item in payload.get("args", [])]
    return []


def main():
    args = _load_args()

    if not ENTRY_POINT:
        print("This tool has no runnable entry point.", file=sys.stderr)
        return 1

    entry_path = os.path.join(REPO_DIR, ENTRY_POINT)
    if not os.path.isfile(entry_path):
        print("This tool's entry point is missing from the bundle.", file=sys.stderr)
        return 1

    sys.argv = [ENTRY_POINT] + args
    os.chdir(REPO_DIR)
    runpy.run_path(entry_path, run_name="__main__")
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''

_registry_cache: Optional[dict[str, list[str]]] = None


def load_registry(path: Optional[Path] = None) -> dict[str, list[str]]:
    global _registry_cache
    if path is None and _registry_cache is not None:
        return _registry_cache

    target = path or get_settings().registry_path
    with open(target, "r") as handle:
        data = yaml.safe_load(handle) or {}

    if path is None:
        _registry_cache = data
    return data


def resolve_apt_packages(system_deps: Iterable[str], registry: Optional[dict[str, list[str]]] = None) -> list[str]:
    active_registry = registry if registry is not None else load_registry()
    resolved: list[str] = []
    for name in system_deps:
        for apt_package in active_registry.get(name, []):
            if apt_package not in resolved:
                resolved.append(apt_package)
    return resolved


def resolve_bundled_binaries(system_deps: Iterable[str]) -> list[str]:
    binaries: list[str] = []
    for name in system_deps:
        for binary in BINARY_NAMES_BY_IMPORT.get(name, []):
            if binary not in binaries:
                binaries.append(binary)
    return binaries


@dataclass
class BuildContext:
    python_version: str
    apt_packages: list[str] = field(default_factory=list)
    pip_flags: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {
            "python_version": self.python_version,
            "apt_packages": list(self.apt_packages),
            "pip_flags": list(self.pip_flags),
        }


class BuildOutcome(BaseModel):
    success: bool
    log: str = ""


def render_dockerfile(context: BuildContext) -> str:
    apt_line = ""
    if context.apt_packages:
        packages = " ".join(context.apt_packages)
        apt_line = (
            f"RUN apt-get update && apt-get install -y --no-install-recommends {packages} "
            "&& rm -rf /var/lib/apt/lists/*\n"
        )

    pip_flags_prefix = f"{' '.join(context.pip_flags)} " if context.pip_flags else ""

    return (
        f"FROM python:{context.python_version}-slim\n"
        f"{apt_line}"
        "WORKDIR /build\n"
        "COPY repo/ repo/\n"
        "RUN python -m venv /output/venv\n"
        "RUN /output/venv/bin/pip install --upgrade pip\n"
        f"RUN /output/venv/bin/pip install {pip_flags_prefix}-r repo/requirements.txt || "
        f"/output/venv/bin/pip install {pip_flags_prefix}-e repo/ || "
        f"/output/venv/bin/pip install {pip_flags_prefix}repo/\n"
        "RUN mkdir -p /output/repo && cp -r repo/. /output/repo/\n"
    )


def _normalize_requirement_name(raw_line: str) -> str:
    return re.split(r"[<>=!~\[; ]", raw_line.strip())[0].strip()


def apply_fix(fix: FixSuggestion, context: BuildContext, repo_dir: Optional[Path] = None) -> BuildContext:
    """Return a new BuildContext with `fix` applied. `edit_requirements` also
    mutates requirements.txt in `repo_dir` directly, since that fix type can't
    be represented purely as build flags."""
    apt_packages = list(context.apt_packages)
    pip_flags = list(context.pip_flags)
    python_version = context.python_version

    if fix.fix_type == "add_apt_package":
        for pkg in fix.fix_payload.get("packages", []):
            if pkg not in apt_packages:
                apt_packages.append(pkg)

    elif fix.fix_type == "pip_flag":
        flag = fix.fix_payload.get("flag")
        flags = fix.fix_payload.get("flags", [flag] if flag else [])
        for f in flags:
            if f and f not in pip_flags:
                pip_flags.append(f)

    elif fix.fix_type == "pin_python_version":
        python_version = fix.fix_payload.get("python_version", python_version)

    elif fix.fix_type == "edit_requirements" and repo_dir is not None:
        req_path = repo_dir / "requirements.txt"
        lines = req_path.read_text().splitlines() if req_path.exists() else []
        remove = set(fix.fix_payload.get("remove", []))
        if remove:
            lines = [line for line in lines if _normalize_requirement_name(line) not in remove]
        for add_line in fix.fix_payload.get("add", []):
            lines.append(add_line)
        req_path.write_text("\n".join(lines) + "\n")

    # "retry" (and any unrecognized fix_type) intentionally makes no changes.

    return BuildContext(python_version=python_version, apt_packages=apt_packages, pip_flags=pip_flags)


def _extract_archive(container, container_path: str, dest_dir: Path) -> None:
    bits, _stat = container.get_archive(container_path)
    buffer = io.BytesIO()
    for chunk in bits:
        buffer.write(chunk)
    buffer.seek(0)

    with tarfile.open(fileobj=buffer, mode="r|*") as tar:
        tar.extractall(dest_dir)

    extracted_root = dest_dir / Path(container_path).name
    if extracted_root.is_dir():
        for item in extracted_root.iterdir():
            target = dest_dir / item.name
            if target.exists():
                if target.is_dir():
                    shutil.rmtree(target)
                else:
                    target.unlink()
            shutil.move(str(item), str(target))
        extracted_root.rmdir()


def _extract_single_file(container, container_path: str, dest_dir: Path) -> None:
    bits, _stat = container.get_archive(container_path)
    buffer = io.BytesIO()
    for chunk in bits:
        buffer.write(chunk)
    buffer.seek(0)

    with tarfile.open(fileobj=buffer, mode="r|*") as tar:
        tar.extractall(dest_dir)


def build_bundle(
    *,
    repo_dir: Path,
    staging_dir: Path,
    tool_id: str,
    context: BuildContext,
    system_deps: Iterable[str],
    docker_client,
) -> BuildOutcome:
    """Build the tool's virtualenv inside a fresh Docker container and extract
    /output into staging_dir/tool_id/. The container (and image) are always
    removed before returning, regardless of outcome."""
    build_context_dir = Path(tempfile.mkdtemp(prefix=f"{tool_id}-ctx-"))
    log_lines: list[str] = []

    try:
        shutil.copytree(repo_dir, build_context_dir / "repo", ignore=shutil.ignore_patterns(".git"))
        (build_context_dir / "Dockerfile").write_text(render_dockerfile(context))

        image_tag = f"toolbox-build-{tool_id}-{uuid.uuid4().hex[:8]}".lower()

        try:
            _image, log_stream = docker_client.images.build(path=str(build_context_dir), tag=image_tag, rm=True)
            for chunk in log_stream:
                if isinstance(chunk, dict) and chunk.get("stream"):
                    log_lines.append(chunk["stream"])
        except docker.errors.BuildError as exc:
            for chunk in getattr(exc, "build_log", []) or []:
                if isinstance(chunk, dict) and chunk.get("stream"):
                    log_lines.append(chunk["stream"])
            log_lines.append(str(exc))
            return BuildOutcome(success=False, log="".join(log_lines))
        except docker.errors.APIError as exc:
            log_lines.append(str(exc))
            return BuildOutcome(success=False, log="".join(log_lines))

        container = None
        try:
            container = docker_client.containers.create(image_tag)
            dest_dir = staging_dir / tool_id
            dest_dir.mkdir(parents=True, exist_ok=True)
            _extract_archive(container, "/output", dest_dir)

            binaries = resolve_bundled_binaries(system_deps)
            if binaries:
                bin_dir = dest_dir / "bin"
                bin_dir.mkdir(exist_ok=True)
                for name in binaries:
                    try:
                        _extract_single_file(container, f"/usr/bin/{name}", bin_dir)
                    except docker.errors.NotFound:
                        continue
        finally:
            if container is not None:
                container.remove(force=True)
            try:
                docker_client.images.remove(image_tag, force=True)
            except Exception:
                pass

        return BuildOutcome(success=True, log="".join(log_lines))
    finally:
        shutil.rmtree(build_context_dir, ignore_errors=True)


def _guess_entry_point_from_run_command(run_command: Optional[str]) -> Optional[str]:
    if not run_command:
        return None
    for part in run_command.strip().split():
        if part.endswith(".py"):
            return part
    return None


def _render_run_py(analysis: ReadmeAnalysis) -> str:
    entry_point = analysis.entry_point or _guess_entry_point_from_run_command(analysis.run_command)
    return RUN_PY_TEMPLATE.format(entry_point=entry_point)


def _pick_icon_color(tool_id: str) -> str:
    return ICON_PALETTE[sum(ord(c) for c in tool_id) % len(ICON_PALETTE)]


def _derive_display_name(tool_id: str) -> str:
    words = re.split(r"[-_]", tool_id)
    return " ".join(word.capitalize() for word in words if word) or tool_id


def _infer_panel_metadata(description: str, apt_packages: Iterable[str]) -> dict:
    text = (description or "").lower()
    deps = set(apt_packages)

    if any(word in text for word in ("download", "youtube", "yt-dlp", " url")):
        return {"panel_type": "url_in_file_out", "input_types": ["url"], "output_types": ["audio", "video"]}
    if any(word in text for word in ("transcri", "speech to text", "speech-to-text")):
        return {"panel_type": "file_in_text_out", "input_types": ["audio", "video"], "output_types": ["text"]}
    if any(word in text for word in ("separat", "stem", "split")) and "ffmpeg" in deps:
        return {"panel_type": "file_in_files_out", "input_types": ["audio"], "output_types": ["files"]}
    return {"panel_type": "file_in_text_out", "input_types": ["audio", "video"], "output_types": ["text"]}


def write_bundle_metadata(
    staging_dir: Path, *, tool_id: str, analysis: ReadmeAnalysis, apt_packages: list[str], platform: str
) -> dict:
    bundle_dir = staging_dir / tool_id
    bundle_dir.mkdir(parents=True, exist_ok=True)

    (bundle_dir / "run.py").write_text(_render_run_py(analysis))

    panel_meta = _infer_panel_metadata(analysis.description, apt_packages)
    manifest = {
        "id": tool_id,
        "name": _derive_display_name(tool_id),
        "version": datetime.now(timezone.utc).strftime("%Y%m%d"),
        "description": analysis.description or "A packaged command-line tool.",
        "python_version": analysis.python_version,
        "entry_point": "run.py",
        "panel_type": panel_meta["panel_type"],
        "input_types": panel_meta["input_types"],
        "output_types": panel_meta["output_types"],
        "runs_offline": True,
        "system_deps": apt_packages,
        "icon_color": _pick_icon_color(tool_id),
        "platform": platform,
    }
    (bundle_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest
